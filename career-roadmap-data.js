function getCareerRoadmapTaskId(day, taskText) {
  let hash = 2166136261;
  for (let i = 0; i < taskText.length; i++) hash = Math.imul(hash ^ taskText.charCodeAt(i), 16777619);
  return 'roadmap-' + day + '-' + (hash >>> 0).toString(36);
}

